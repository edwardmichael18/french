const M = { g: 'm' }, F = { g: 'f' };
const row = ([fr, en, ex, note, extra]) => {
  const it = { fr, en };
  if (ex) it.ex = ex;
  if (note) it.note = note;
  Object.assign(it, extra || {});
  // Pairs ("le médecin / la médecin", "un / une élève") cover both genders: no badge.
  if (!it.g && !fr.includes(' / ')) { const m = fr.match(/^(le|la|un|une)\s/); if (m) it.g = /^(le|un)$/.test(m[1]) ? 'm' : 'f'; }
  return it;
};
// Masculine → feminine pair shown as "m / f"; the drill asks for the feminine.
const pair = (m, f, en, note, ex) => row([`${m} / ${f}`, en, ex, note, { fem: f, say: `${m}, ${f}` }]);
const group = (title, rows) => ({ title, items: rows.map(r => (r.fr ? r : row(r))) });

